'Check input hashes and format the estimates, intervals and p values in Table 2.'
from __future__ import annotations

import csv

import hashlib

import math

from pathlib import Path

STRATEGIES = {'p50': 'p50', 'pollitt': 'Pollitt', 'hybrid': 'Hybrid', 'random': 'Random'}

def verified_csv(directory: Path, name: str) -> list[dict[str, str]]:
    'Read a nonempty table only after its file hash matches the supplied manifest.'
    hashes = {}
    for line in (directory / 'SHA256SUMS').read_text().splitlines():
        digest, filename = line.split(maxsplit=1)
        filename = filename.lstrip('*')
        if filename in hashes:
            raise ValueError(f'duplicate manifest entry: {filename}')
        hashes[filename] = digest
    if name not in hashes:
        raise ValueError(f'{name}: missing manifest entry')
    path = directory / name
    if hashlib.sha256(path.read_bytes()).hexdigest() != hashes[name]:
        raise ValueError(f'{name}: SHA256 mismatch')
    with path.open(newline='') as stream:
        rows = list(csv.DictReader(stream))
    if not rows:
        raise ValueError(f'{name}: empty table')
    return rows

def validate(rows, expected_count, family=None):
    required = {'contrast_id', 'estimate', 'ci95_low', 'ci95_high',
                'df_satterthwaite', 'n_prompts', 'n_cells', 'status'}
    if len(rows) != expected_count:
        raise ValueError(f'expected {expected_count} rows; found {len(rows)}')
    seen = set()
    for row in rows:
        if not required <= row.keys():
            raise ValueError('missing inferential columns')
        key = (row.get('analysis'), row['contrast_id'], row.get('outcome'),
               row.get('window'))
        if key in seen:
            raise ValueError(f'duplicate contrast: {key}')
        seen.add(key)
        if (row['n_prompts'], row['n_cells'], row['status']) != ('16', '96', 'estimable'):
            raise ValueError(f'incomplete contrast support: {key}')
        lo, est, hi, df = [float(row[k]) for k in ('ci95_low', 'estimate', 'ci95_high', 'df_satterthwaite')]
        if not all(math.isfinite(v) for v in (lo, est, hi, df)) or not lo <= est <= hi or df <= 0:
            raise ValueError(f'invalid interval: {key}')
        if family is not None:
            if row.get('family') != family or row.get('reason') != 'complete_target_support':
                raise ValueError(f'wrong primary family or support: {key}')
            p, ph = float(row['p_value']), float(row['p_holm'])
            if not 0 <= p <= ph <= 1:
                raise ValueError(f'invalid adjusted p: {key}')

def number(value, scale=1., digits=3, signed=False):
    value = float(value) / scale
    
    if value != 0 and abs(value) < 0.5 * 10 ** (-digits):
        coefficient, exponent = f'{value:.2e}'.split('e')
        return rf'{coefficient}\times10^{{{int(exponent)}}}'
    rendered = f'{value:+.{digits}f}' if signed else f'{value:.{digits}f}'
    
    
    if rendered.startswith(('0.', '+0.', '-0.')):
        rendered = rendered.replace('0.', '.', 1)
    return rendered

def pvalue(value):
    value = float(value)
    if value < .001:
        return r'< .001'
    rendered = f'{value:.3f}'
    return '.' + rendered[2:] if rendered.startswith('0.') else rendered

def contrast_label(identifier):
    if ':' in identifier:
        estimator, identifier = identifier.split(':', 1)
        return estimator + ': ' + contrast_label(identifier)
    left, right = identifier.split('-')
    return f'{STRATEGIES.get(left, left)} $-$ {STRATEGIES.get(right, right)}'

def row_tex(row, *, scale=1., pcol='p_holm', label=None):
    label = contrast_label(row['contrast_id']) if label is None else label
    estimate = number(row['estimate'], scale, signed=True)
    lo = number(row['ci95_low'], scale)
    hi = number(row['ci95_high'], scale)
    df = f"{float(row['df_satterthwaite']):g}"
    return rf'{label} & ${estimate}$ & $[{lo},\ {hi}]$ & {df} & ${pvalue(row[pcol])}$ \\'

def table(caption, label, body, note, pheader=r'$p_{\mathrm{Holm}}$'):
    return '\n'.join([
        '% Generated by build_results_tables.py; do not edit by hand.',
        r'\begin{table}[htbp]', r'\centering', rf'\caption{{{caption}}}',
        rf'\label{{{label}}}', r'\small', r'\setlength{\tabcolsep}{4pt}',
        r'\begin{tabular}{@{}l r l r r@{}}', r'\toprule',
        rf'Contrast & Difference & 95\% CI & \textit{{df}} & {pheader} \\', r'\midrule',
        *body, r'\bottomrule', r'\end{tabular}', r'\par\smallskip',
        r'\begin{minipage}{\linewidth}', r'\footnotesize',
        rf'\textit{{Note.}} {note}', r'\end{minipage}', r'\end{table}', ''])

def group(text):
    return rf'\multicolumn{{5}}{{@{{}}l}}{{\textit{{{text}}}}} \\'

